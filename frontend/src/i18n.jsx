const LanguageContext = createContext();
export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() =>
    localStorage.getItem("maak-language") === "ar" ? "ar" : "en",
  );
  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    localStorage.setItem("maak-language", language);
  }, [language]);
  const t = (key) => (language === "ar" ? ar[key] : en[key]) ?? en[key] ?? key;
  const date = (value) =>
    value
      ? new Intl.DateTimeFormat(language === "ar" ? "ar-LB" : "en-GB", {
          dateStyle: "medium",
          timeStyle: "short",
          timeZone: "Asia/Beirut",
        }).format(new Date(value))
      : t("unknown");
  const error = (e) =>
    t(`error_${e.code}`) !== `error_${e.code}`
      ? t(`error_${e.code}`)
      : e.message;
  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, date, error }}>
      {children}
    </LanguageContext.Provider>
  );
}
export const useLanguage = () => useContext(LanguageContext);
